/**
 * Lightweight W3C DTCG (Design Tokens Community Group) -> CSS/TS generator.
 *
 * Single source of truth = the `*.tokens.json` files. Everything the UI uses
 * (CSS custom properties + typed TS references) is generated from them, so no
 * design value is ever hardcoded in a component.
 *
 * Intentionally dependency-free and pure, so it is trivially testable.
 */

export interface FlatToken {
  /** Token path, e.g. ['color', 'accent', 'default']. */
  path: string[];
  /** DTCG `$type` (inherited from the nearest ancestor group if not local). */
  type: string | null;
  /** Raw `$value` — either a literal or an alias like `{color.brand.600}`. */
  value: string;
}

export interface GenerateResult {
  css: string;
  js: string;
  dts: string;
  /** Map of camelCase key -> `var(--token-name)` reference. */
  tokens: Record<string, string>;
}

type JsonObject = { [key: string]: unknown };

const ALIAS_RE = /^\{([^}]+)\}$/;

export function isAlias(value: string): boolean {
  return ALIAS_RE.test(value.trim());
}

export function aliasToPath(value: string): string[] {
  const match = ALIAS_RE.exec(value.trim());
  if (!match || match[1] === undefined) {
    throw new Error(`Not an alias: ${value}`);
  }
  return match[1].split('.');
}

/** Default namespace prefix (isolates tokens on third-party host pages). */
export const DEFAULT_PREFIX = 'cq';

/** `['color','status','in-progress']` -> `--cq-color-status-in-progress`. */
export function cssVarName(path: string[], prefix: string = DEFAULT_PREFIX): string {
  return `--${prefix}-${path.join('-')}`;
}

/** `['font','size','2xl']` -> `fontSize2xl`. */
export function camelKey(path: string[]): string {
  const words = path.join('-').split('-').filter(Boolean);
  return words
    .map((word, index) =>
      index === 0 ? word.toLowerCase() : word.charAt(0).toUpperCase() + word.slice(1),
    )
    .join('');
}

/** Flatten a DTCG document into a list of tokens, inheriting `$type`. */
export function flatten(
  node: JsonObject,
  inheritedType: string | null = null,
  prefix: string[] = [],
): FlatToken[] {
  const out: FlatToken[] = [];
  const groupType = typeof node.$type === 'string' ? node.$type : inheritedType;

  for (const [key, value] of Object.entries(node)) {
    if (key.startsWith('$')) continue;
    if (value === null || typeof value !== 'object') continue;

    const child = value as JsonObject;
    const path = [...prefix, key];

    if ('$value' in child) {
      const localType = typeof child.$type === 'string' ? child.$type : groupType;
      out.push({ path, type: localType, value: String(child.$value) });
    } else {
      out.push(...flatten(child, groupType, path));
    }
  }

  return out;
}

/** Resolve a token value to its CSS form (alias -> `var()`, literal as-is). */
export function resolveCssValue(value: string, prefix: string = DEFAULT_PREFIX): string {
  if (isAlias(value)) {
    return `var(${cssVarName(aliasToPath(value), prefix)})`;
  }
  return value;
}

const AUTOGEN_HEADER =
  '/* GENERATED by @croquis/tokens — do not edit. Source: src/*.tokens.json */';

export interface GenerateOptions {
  /** CSS variable namespace prefix (default "cq"). */
  prefix?: string;
  /**
   * Selector the `:root`-level custom properties are attached to.
   * Default `:where(:root, :host)` so the same sheet works in the document
   * (dashboard) and inside a widget's shadow root.
   */
  selector?: string;
}

/**
 * Generate CSS/JS/DTS from one or more DTCG documents (order preserved).
 * Throws on duplicate names or on aliases that point to unknown tokens.
 */
export function generate(documents: JsonObject[], options: GenerateOptions = {}): GenerateResult {
  const prefix = options.prefix ?? DEFAULT_PREFIX;
  const selector = options.selector ?? ':where(:root, :host)';
  const flat = documents.flatMap((doc) => flatten(doc));

  // Detect duplicate CSS variable names and camelCase key collisions.
  const varNames = new Set<string>();
  const camelKeys = new Set<string>();
  for (const token of flat) {
    const varName = cssVarName(token.path, prefix);
    if (varNames.has(varName)) {
      throw new Error(`Duplicate token: ${varName}`);
    }
    varNames.add(varName);

    const key = camelKey(token.path);
    if (camelKeys.has(key)) {
      throw new Error(`Duplicate camelCase token key: ${key} (from ${token.path.join('.')})`);
    }
    camelKeys.add(key);
  }

  // Validate aliases resolve to a known token.
  for (const token of flat) {
    if (isAlias(token.value)) {
      const target = cssVarName(aliasToPath(token.value), prefix);
      if (!varNames.has(target)) {
        throw new Error(
          `Alias ${token.value} on ${token.path.join('.')} points to unknown token ${target}`,
        );
      }
    }
  }

  const cssLines = flat.map(
    (token) => `  ${cssVarName(token.path, prefix)}: ${resolveCssValue(token.value, prefix)};`,
  );
  const css = `${AUTOGEN_HEADER}\n${selector} {\n${cssLines.join('\n')}\n}\n`;

  const tokens: Record<string, string> = {};
  for (const token of flat) {
    tokens[camelKey(token.path)] = `var(${cssVarName(token.path, prefix)})`;
  }

  const jsEntries = Object.entries(tokens)
    .map(([key, value]) => `  ${key}: ${JSON.stringify(value)},`)
    .join('\n');
  const js = `${AUTOGEN_HEADER}\nexport const tokens = {\n${jsEntries}\n};\n\nexport default tokens;\n`;

  const dtsEntries = Object.keys(tokens)
    .map((key) => `  readonly ${key}: string;`)
    .join('\n');
  const dts = `${AUTOGEN_HEADER}\nexport declare const tokens: {\n${dtsEntries}\n};\nexport default tokens;\n`;

  return { css, js, dts, tokens };
}
