export type Locale = 'en' | 'ja';
const dictionaries: Record<Locale, Record<MessageKey, string>> = { en, ja };

function initialLocale(): Locale {
  try {
    const saved = localStorage.getItem('croquis:locale');
    if (saved === 'en' || saved === 'ja') return saved;
  } catch {
    // storage unavailable
  }
  return navigator.language.toLowerCase().startsWith('ja') ? 'ja' : 'en';
}

export const locale = signal<Locale>(typeof window === 'undefined' ? 'en' : initialLocale());

export function setLocale(next: Locale): void {
  locale.value = next;
  document.documentElement.lang = next;
  try {
    localStorage.setItem('croquis:locale', next);
  } catch {
    // ignore
  }
}

/** Translate with `{placeholder}` interpolation. Reading `locale` makes components re-render on change. */
export function t(key: MessageKey, values: Record<string, string | number> = {}): string {
  const template = dictionaries[locale.value][key] ?? en[key];
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? `{${name}}`));
}

const relative = computed(() => new Intl.RelativeTimeFormat(locale.value, { numeric: 'auto' }));

/** "3m ago", "yesterday", or a date for anything older than a week. */
export function timeAgo(ms: number): string {
  const diff = Date.now() - ms;
  const minute = 60_000;
  if (diff < minute) return t('time.justNow');
  if (diff < 60 * minute) return relative.value.format(-Math.round(diff / minute), 'minute');
  if (diff < 24 * 60 * minute)
    return relative.value.format(-Math.round(diff / (60 * minute)), 'hour');
  if (diff < 7 * 24 * 60 * minute)
    return relative.value.format(-Math.round(diff / (24 * 60 * minute)), 'day');
  return formatDate(ms);
}

export function formatDate(ms: number): string {
  return new Intl.DateTimeFormat(locale.value, {
    year: 'numeric',
    month: 'short',
    day: 'numeric',
  }).format(ms);
}

export function formatDateTime(ms: number): string {
  return new Intl.DateTimeFormat(locale.value, { dateStyle: 'medium', timeStyle: 'short' }).format(
    ms,
  );
}
